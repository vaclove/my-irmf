/**
 * Per-movie file management: /api/movies/:movieId/files
 *
 * Primary copies live in Azure Blob (see services/movieStorage.js); Google
 * Drive keeps the human-facing backup (masters, subtitle mirrors) and remains
 * the store for legacy rows of editions that never moved.
 *
 * Mounted with mergeParams so :movieId is available. Drive-dependent endpoints
 * return 503 when Google Drive is not configured; GET degrades to DB rows with
 * a drive_error flag so the UI always renders known status.
 */

