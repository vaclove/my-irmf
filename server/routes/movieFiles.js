// Timing lines are copied verbatim from the parsed source, so accept the SRT
// form with optional trailing cue settings/coordinates.
const CUE_TIMING_RE =
  /^\d{1,2}:\d{2}:\d{2}[,.]\d{1,3}\s+-->\s+\d{1,2}:\d{2}:\d{2}[,.]\d{1,3}(\s.*)?$/;

// PUT /subtitles/:lang/cues — save edited cue texts (timings never change).
// Body: { cues, base_md5, overwrite_drive? }. 409 with code 'changed' (the
// file moved on since it was loaded) or 'drive_changed' (the Drive copy was
// edited outside the app; resend with overwrite_drive to replace it).
router.put('/subtitles/:lang/cues', async (req, res) => {
  const { movieId, lang } = req.params;
  if (!SUBTITLE_LANGS.includes(lang)) {
    return res.status(400).json({ error: 'Unsupported subtitle language' });
  }
  if (!googleDrive.isConfigured()) return notConfigured(res);
  try {
    const { cues, base_md5, overwrite_drive } = req.body || {};
    if (!Array.isArray(cues) || cues.length === 0) {
      return res.status(400).json({ error: 'cues must be a non-empty array' });
    }
    if (!base_md5) {
      return res.status(400).json({ error: 'base_md5 is required' });
    }
    for (const cue of cues) {
      if (
        !cue ||
        typeof cue.timing !== 'string' ||
        !CUE_TIMING_RE.test(cue.timing.trim()) ||
        typeof cue.text !== 'string'
      ) {
        return res
          .status(400)
          .json({ error: 'Each cue needs a valid timing line and a text string' });
      }
    }

    const movie = await loadMovie(movieId);
    if (!movie) return res.status(404).json({ error: 'Movie not found' });
    const row = await loadSubtitleRow(movieId, lang);
    if (!row) return res.status(404).json({ error: 'Subtitles not found' });

    const { conflict, etag } = await checkUnchanged(movieId, row, base_md5, {
      overwriteDrive: overwrite_drive === true,
    });
    if (conflict) return res.status(409).json(conflict);

    const ext = rowExt(row);
    const clean = cues.map((c) => ({ timing: c.timing.trim(), text: c.text }));
    const text = ext === 'vtt' ? serializeVtt(clean) : serializeSrt(clean);
    const body = Buffer.from(text, 'utf8');
    if (body.length > MAX_SUBTITLE_BYTES) {
      return res.status(413).json({ error: 'Subtitles file is too large' });
    }

    let fresh;
    try {
      fresh = await writeSubtitles(req, movie, row.file_kind, body, { ext, ifMatch: etag });
    } catch (writeError) {
      // The blob changed between the check and the write (ETag mismatch).
      if (writeError.statusCode === 412) {
        return res.status(409).json({
          code: 'changed',
          error: 'Subtitles were changed in the app while saving. Reload to get the current version.',
        });
      }
      throw writeError;
    }
    await auditFileChange(req, 'edit_subtitles', {
      before: row,
      after: fresh,
      extra: { cue_count: clean.length, overwrite_drive: overwrite_drive === true },
    });

    // Reconcile open quality flags against the saved text (non-fatal):
    // suggestion applied -> accepted; text changed some other way (or the
    // file shape changed) -> stale; untouched -> stays open, re-pinned to
    // the new checksum so later saves don't orphan it.
    try {
      const openFlags = await pool.query(
        `SELECT id, cue_index, target_text, suggestion FROM subtitle_quality_flags
         WHERE movie_id = $1 AND lang = $2 AND status = 'open'`,
        [movieId, lang]
      );
      const resolvedBy = req.user?.email || null;
      for (const flag of openFlags.rows) {
        const saved = clean[flag.cue_index];
        if (!saved) {
          await pool.query(
            `UPDATE subtitle_quality_flags SET status = 'stale' WHERE id = $1`,
            [flag.id]
          );
        } else if (saved.text === flag.target_text) {
          await pool.query(
            `UPDATE subtitle_quality_flags SET file_md5 = $2, file_drive_id = $3 WHERE id = $1`,
            [flag.id, fresh?.md5_checksum || null, movieStorage.fileRef(fresh)]
          );
        } else if (flag.suggestion && saved.text === flag.suggestion) {
          await pool.query(
            `UPDATE subtitle_quality_flags SET status = 'accepted',
               resolved_at = CURRENT_TIMESTAMP, resolved_by = $2 WHERE id = $1`,
            [flag.id, resolvedBy]
          );
        } else {
          await pool.query(
            `UPDATE subtitle_quality_flags SET status = 'stale' WHERE id = $1`,
            [flag.id]
          );
        }
      }
    } catch (flagError) {
      logError(flagError, req, { operation: 'reconcile_subtitle_quality_flags', movieId });
    }

    res.json({ file: fresh });
  } catch (error) {
    logError(error, req, { operation: 'save_subtitle_cues', movieId });
    if (!res.headersSent) res.status(500).json({ error: error.message });
  }
});

// POST /subtitles/:lang/adopt-drive — the Drive copy of an Azure subtitle file
// was edited outside the app: make that version the app's version.
router.post('/subtitles/:lang/adopt-drive', async (req, res) => {
  const { movieId, lang } = req.params;
  if (!SUBTITLE_LANGS.includes(lang)) {
    return res.status(400).json({ error: 'Unsupported subtitle language' });
  }
  if (!googleDrive.isConfigured()) return notConfigured(res);
  try {
    const movie = await loadMovie(movieId);
    if (!movie) return res.status(404).json({ error: 'Movie not found' });
    const row = await loadSubtitleRow(movieId, lang);
    if (!row || row.storage !== 'azure' || !row.drive_file_id) {
      return res.status(404).json({ error: 'These subtitles have no Drive copy to use' });
    }
    const meta = await googleDrive.getFileMetadata(row.drive_file_id);
    const body = await movieStorage.readBuffer(row.drive_file_id);
    const ext = extensionOf(meta.name) === 'vtt' ? 'vtt' : 'srt';
    try {
      parseSubtitles(body.toString('utf8'), ext);
    } catch (parseError) {
      return res.status(422).json({ error: `The Drive copy is not valid subtitles: ${parseError.message}` });
    }
    const sameFormat = rowExt(row) === ext;
    const blobName = sameFormat ? row.blob_name : movieStorage.blobNameFor(movie, row.file_kind, ext);
    const written = await movieStorage.uploadBuffer(blobName, body, {
      fileKind: row.file_kind,
      contentType: `${movieStorage.subtitleMime(ext)}; charset=utf-8`,
    });
    await movieStorage.upsertAzureRow(movieId, row.file_kind, {
      blobName,
      fileName: conventionFileName(movie, row.file_kind, ext),
      size: written.size,
      mimeType: movieStorage.subtitleMime(ext),
      md5: written.md5,
      etag: written.etag,
      drive: { id: row.drive_file_id, md5: meta.md5Checksum || written.md5 },
    });
    if (!sameFormat) await movieStorage.deleteBlob(row.blob_name).catch(() => {});
    await staleOpenFlags(req, movieId, lang);
    const fresh = await loadSubtitleRow(movieId, lang);
    await auditFileChange(req, 'adopt_drive_subtitles', { before: row, after: fresh });
    res.json({ file: fresh });
  } catch (error) {
    if (error.statusCode === 413) {
      return res.status(413).json({ error: error.message });
    }
    logError(error, req, { operation: 'adopt_drive_subtitles', movieId });
    if (!res.headersSent) res.status(500).json({ error: error.message });
  }
});

// POST /subtitles/:lang/use-synced — make the alass-synced copy the original:
// its cues overwrite the original in place, then the synced copy is removed.
// Open flags on the synced copy move over to the original. Body:
// { overwrite_drive? } — see PUT /cues for the 409 codes.
router.post('/subtitles/:lang/use-synced', async (req, res) => {
  const { movieId, lang } = req.params;
  if (!['cs', 'en'].includes(lang)) {
    return res.status(400).json({ error: 'Unsupported subtitle language' });
  }
  if (!googleDrive.isConfigured()) return notConfigured(res);
  try {
    const movie = await loadMovie(movieId);
    if (!movie) return res.status(404).json({ error: 'Movie not found' });

    const synced = await loadSubtitleRow(movieId, `${lang}_synced`);
    if (!synced) return res.status(404).json({ error: 'No synced subtitles to use' });

    const activeSync = await pool.query(
      `SELECT id FROM subtitle_sync_jobs
       WHERE movie_id = $1 AND subtitle_kind = $2 AND status IN ('pending', 'running')`,
      [movieId, `subtitles_${lang}`]
    );
    if (activeSync.rows.length > 0) {
      return res.status(409).json({ error: 'A sync job is still running for this track' });
    }

    const { text: syncedText } = await movieStorage.readSubtitleRow(synced);
    let cues;
    try {
      cues = parseSubtitles(syncedText, 'srt');
    } catch (parseError) {
      return res.status(422).json({ error: parseError.message });
    }

    const original = await loadSubtitleRow(movieId, lang);
    const kind = `subtitles_${lang}`;
    // Keep the original's format; a missing original becomes a fresh .srt.
    const ext = original && rowExt(original) === 'vtt' ? 'vtt' : 'srt';
    const body = Buffer.from(ext === 'vtt' ? serializeVtt(cues) : serializeSrt(cues), 'utf8');

    let etag;
    if (original) {
      const check = await checkUnchanged(movieId, original, original.md5_checksum, {
        overwriteDrive: req.body?.overwrite_drive === true,
      });
      if (check.conflict) return res.status(409).json(check.conflict);
      etag = check.etag;
    }
    const fresh = await writeSubtitles(req, movie, kind, body, { ext, ifMatch: etag });
    await auditFileChange(req, 'use_synced_subtitles', {
      before: original,
      after: fresh,
      extra: { replaced_by: synced.file_name },
    });

    // Remove the synced copy (blob + Drive mirror, or the legacy Drive file).
    if (synced.storage === 'azure') {
      await movieStorage.deleteBlob(synced.blob_name).catch(() => {});
    }
    if (synced.drive_file_id) {
      await googleDrive.trashFile(synced.drive_file_id).catch((trashError) => {
        if (!isDriveNotFound(trashError)) {
          logError(trashError, req, { operation: 'trash_promoted_synced_subtitles', movieId });
        }
      });
    }
    await pool.query('DELETE FROM movie_files WHERE movie_id = $1 AND file_kind = $2', [
      movieId,
      `${kind}_synced`,
    ]);

    // The original's findings described the old text; the synced copy's
    // findings still match cue-for-cue, so re-home them onto the original.
    await staleOpenFlags(req, movieId, lang);
    try {
      await pool.query(
        `UPDATE subtitle_quality_flags SET lang = $2, file_drive_id = $3, file_md5 = $4
         WHERE movie_id = $1 AND lang = $5 AND status = 'open'`,
        [movieId, lang, movieStorage.fileRef(fresh), fresh.md5_checksum || null, `${lang}_synced`]
      );
    } catch (flagError) {
      logError(flagError, req, { operation: 'rehome_subtitle_quality_flags', movieId });
    }

    res.json({ file: await loadSubtitleRow(movieId, lang) });
  } catch (error) {
    if (error.statusCode === 413) {
      return res.status(413).json({ error: error.message });
    }
    if (error.statusCode === 412) {
      return res.status(409).json({ code: 'changed', error: 'The original subtitles changed while replacing. Try again.' });
    }
    logError(error, req, { operation: 'use_synced_subtitles', movieId });
    if (!res.headersSent) res.status(500).json({ error: error.message });
  }
});

