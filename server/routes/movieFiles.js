// POST /transfers/:jobId/retry — re-run a failed/cancelled transfer.
router.post('/transfers/:jobId/retry', async (req, res) => {
  const { movieId, jobId } = req.params;
  try {
    const result = await pool.query(
      'SELECT * FROM movie_file_transfer_jobs WHERE id = $1 AND movie_id = $2',
      [jobId, movieId]
    );
    const old = result.rows[0];
    if (!old) return res.status(404).json({ error: 'Transfer not found' });
    if (!['failed', 'cancelled'].includes(old.status)) {
      return res.status(409).json({ error: 'Only failed or cancelled transfers can be retried' });
    }
    const row = await movieStorage.loadRow(movieId, old.file_kind);
    let sourceRef = old.source_ref;
    if (old.direction === 'azure_to_drive') {
      // Back up the master's current version, not the one that failed.
      if (!row || row.storage !== 'azure') {
        return res.status(400).json({ error: 'Nothing in Azure to back up' });
      }
      sourceRef = movieStorage.fileRef(row);
    } else {
      // An import may only be retried while the slot still holds what it was
      // meant to replace: the same legacy Drive row (automatic imports), or
      // nothing newer than the original request (explicit imports).
      const stillLegacy = !row || (row.storage === 'drive' && row.drive_file_id === old.source_ref);
      const untouched = !row || new Date(row.updated_at) <= new Date(old.created_at);
      if (!(old.replace_existing ? untouched : stillLegacy)) {
        return res.status(409).json({ error: 'The file was replaced since; this copy is no longer needed' });
      }
    }
    const job = await fileTransferQueue.enqueue({
      movieId,
      fileKind: old.file_kind,
      direction: old.direction,
      sourceRef,
      transcodeAfter: old.transcode_after,
      replaceExisting: old.replace_existing,
      createdBy: req.user?.email,
    });
    if (!job) return res.status(409).json({ error: 'This transfer is already running' });
    await pool.query('UPDATE movie_file_transfer_jobs SET dismissed_at = CURRENT_TIMESTAMP WHERE id = $1', [
      jobId,
    ]);
    res.status(201).json({ job });
  } catch (error) {
    logError(error, req, { operation: 'retry_file_transfer', movieId });
    res.status(500).json({ error: error.message });
  }
});

