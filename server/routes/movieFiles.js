// DELETE /:fileKind — drop the row. Azure: the blob is deleted (recoverable
// for 14 days via soft delete). The Drive copy is trashed, or renamed to
// {name}.removed.{ext} — the folder scan that runs on every page load would
// otherwise re-adopt it by its convention name and the asset would come back.
router.delete('/:fileKind', async (req, res) => {
  const { movieId, fileKind } = req.params;
  const removeFromDrive = req.query.remove_from_drive === 'true';
  try {
    if (!FILE_KINDS.includes(fileKind)) {
      return res.status(400).json({ error: 'Invalid file kind' });
    }
    const row = await movieStorage.loadRow(movieId, fileKind);
    if (!row) return res.status(404).json({ error: 'File not found' });

    const active = await pool.query(
      `SELECT id FROM movie_file_transfer_jobs
       WHERE movie_id = $1 AND file_kind = $2 AND status IN ('pending', 'running')`,
      [movieId, fileKind]
    );
    if (active.rows.length > 0) {
      return res.status(409).json({ error: 'A copy of this file is in progress; try again when it finishes' });
    }

    let renamedTo = null;
    if (row.drive_file_id) {
      if (googleDrive.isConfigured()) {
        renamedTo = await detachDriveCopy(row.drive_file_id, { trash: removeFromDrive });
      } else if (removeFromDrive) {
        return notConfigured(res);
      }
    }
    if (row.storage === 'azure') {
      await movieStorage.deleteBlob(row.blob_name);
    }

    await pool.query(
      'DELETE FROM movie_files WHERE movie_id = $1 AND file_kind = $2',
      [movieId, fileKind]
    );
    if (fileKind.startsWith('subtitles_')) {
      await staleOpenFlags(req, movieId, fileKind.replace('subtitles_', ''));
    }
    await auditFileChange(req, 'delete', {
      before: row,
      action: 'DELETE',
      extra: { trashed_on_drive: removeFromDrive, renamed_to: renamedTo },
    });
    res.json({ message: 'File removed', trashed: removeFromDrive, renamed_to: renamedTo });
  } catch (error) {
    logError(error, req, { operation: 'delete_movie_file', movieId });
    res.status(500).json({ error: error.message });
  }
});

