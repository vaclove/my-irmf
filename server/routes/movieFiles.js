const router = express.Router({ mergeParams: true });

const { MAX_SUBTITLE_BYTES } = movieStorage;
const SUBTITLE_KINDS = ['subtitles_cs', 'subtitles_en'];
// Languages accepted by the /subtitles/:lang routes (subtitles_{lang} kinds).
// Synced variants are machine-generated by the sync worker but serve/edit the same way.
const SUBTITLE_LANGS = ['cs', 'en', 'cs_synced', 'en_synced'];
// File kinds that are playable video and can be streamed to the browser.
const STREAMABLE_KINDS = ['movie', 'movie_proxy'];

function notConfigured(res) {
  return res.status(503).json({ error: 'Google Drive is not configured' });
}

/** Drive "file not found" (already deleted/trashed elsewhere). */
function isDriveNotFound(error) {
  return error?.code === 404 || error?.response?.status === 404;
}

/** The manual "files ready" mark from a loadMovie() row, or null. */
function readyOf(movie) {
  return movie.files_ready_at
    ? { at: movie.files_ready_at, by: movie.files_ready_by || null }
    : null;
}

/**
 * Ensure a file's type matches the kind slot it will occupy:
 * subtitle kinds require .srt/.vtt; the movie kind requires a video file.
 * Returns an error string, or null if valid.
 */
function validateKindForFile(fileKind, fileName, mimeType) {
  const ext = extensionOf(fileName);
  if (
    (SUBTITLE_KINDS.includes(fileKind) || fileKind.endsWith('_synced')) &&
    !SUBTITLE_EXTENSIONS.includes(ext)
  ) {
    return 'Subtitles must be .srt or .vtt';
  }
  if (fileKind === 'movie' && !isVideoFile(fileName, mimeType)) {
    return 'Movie asset must be a video file';
  }
  if (fileKind === 'movie_proxy' && ext !== 'mp4') {
    return 'Preview proxy must be an .mp4';
  }
  return null;
}

/** Load a movie row with edition_year, or null. */
async function loadMovie(movieId) {
  const res = await pool.query(
    `SELECT m.id, m.name_cs, m.name_en, m.drive_folder_id, m.files_ready_at,
            m.files_ready_by, e.year AS edition_year
     FROM movies m JOIN editions e ON m.edition_id = e.id
     WHERE m.id = $1`,
    [movieId]
  );
  return res.rows[0] || null;
}

/** Subtitle format of a row's primary copy. */
function rowExt(row) {
  return extensionOf(row.storage === 'azure' ? row.blob_name : row.file_name);
}

/**
 * Write subtitles through movieStorage (Azure + Drive mirror, or legacy
 * Drive) and keep the subtitle cache warm for Drive-stored results.
 */
async function writeSubtitles(req, movie, fileKind, body, { ext, ifMatch } = {}) {
  const fresh = await movieStorage.writeSubtitleFile(movie, fileKind, body, {
    ext,
    ifMatch,
    onMirrorError: (mirrorError) =>
      logError(mirrorError, req, { operation: 'mirror_subtitles_to_drive', movieId: movie.id }),
  });
  if (fresh.storage === 'drive') {
    await cacheSubtitleTextSafe(
      fresh.drive_file_id,
      { bytes: body, md5: fresh.md5_checksum || null },
      (cacheError) => logError(cacheError, req, { operation: 'cache_subtitle_text', movieId: movie.id })
    );
  }
  return fresh;
}

/**
 * Has the file been changed behind the app's back since `baseMd5`?
 *   Azure rows: the blob's md5 (concurrent edit in the app) and the Drive
 *     mirror's md5 vs the last one the app wrote (edit on Drive), unless
 *     overwriteDrive.
 *   Drive rows: the Drive file's md5; on a mismatch the pointer row is
 *     refreshed so the next read re-downloads instead of serving cached text.
 * @returns {Promise<{conflict: null|{code: string, error: string}, etag?: string}>}
 */
async function checkUnchanged(movieId, row, baseMd5, { overwriteDrive = false } = {}) {
  if (row.storage === 'azure') {
    const props = await movieStorage.getProperties(row.blob_name);
    const blobMd5 = movieStorage.base64ToHex(props.contentMD5);
    if (baseMd5 && blobMd5 && blobMd5 !== baseMd5) {
      return {
        conflict: {
          code: 'changed',
          error:
            'Subtitles were changed in the app since you loaded them. ' +
            'Reload to get the current version (your unsaved edits will be lost).',
        },
      };
    }
    if (row.drive_file_id && !overwriteDrive) {
      const meta = await googleDrive.getFileMetadata(row.drive_file_id).catch((e) => {
        if (isDriveNotFound(e)) return null;
        throw e;
      });
      if (meta?.md5Checksum && row.drive_md5_checksum && meta.md5Checksum !== row.drive_md5_checksum) {
        return {
          conflict: {
            code: 'drive_changed',
            error:
              'The Drive copy of these subtitles was edited outside the app. ' +
              'Use the Drive version, or overwrite it with yours.',
          },
        };
      }
    }
    return { conflict: null, etag: props.etag };
  }

  const meta = await googleDrive.getFileMetadata(row.drive_file_id);
  if (meta.md5Checksum && baseMd5 && meta.md5Checksum !== baseMd5) {
    await upsertFileRow(movieId, row.file_kind, meta);
    return {
      conflict: {
        code: 'changed',
        error:
          'Subtitles were changed on Drive outside the app since you loaded them. ' +
          'Reload the editor to get the current version (your unsaved edits will be lost).',
      },
    };
  }
  return { conflict: null };
}

/**
 * Mark a subtitle track's open quality flags stale (its file was replaced or
 * removed, so the findings no longer describe it). Non-fatal.
 */
async function staleOpenFlags(req, movieId, lang) {
  try {
    await pool.query(
      `UPDATE subtitle_quality_flags SET status = 'stale'
       WHERE movie_id = $1 AND lang = $2 AND status = 'open'`,
      [movieId, lang]
    );
  } catch (flagError) {
    logError(flagError, req, { operation: 'stale_subtitle_quality_flags', movieId });
  }
}

/** The audit-relevant fields of a movie_files row, or null. */
function auditSnapshot(row) {
  if (!row) return null;
  return {
    file_kind: row.file_kind,
    file_name: row.file_name,
    file_size: row.file_size,
    storage: row.storage,
    md5_checksum: row.md5_checksum,
  };
}

/**
 * Record a file change in the audit log (resource movie_files, id = the
 * movie). Action is CREATE when the slot was empty, else UPDATE, unless given.
 */
function auditFileChange(req, operation, { before = null, after = null, action, extra = {} } = {}) {
  return logAuditEvent({
    req,
    action: action || (before ? 'UPDATE' : 'CREATE'),
    resource: 'movie_files',
    resourceId: req.params.movieId,
    oldData: auditSnapshot(before),
    newData: (after || Object.keys(extra).length) ? { ...auditSnapshot(after), ...extra } : null,
    additionalMetadata: { operation },
  });
}

/** Load the movie_files row for a subtitle language, or null. */
async function loadSubtitleRow(movieId, lang) {
  return movieStorage.loadRow(movieId, `subtitles_${lang}`);
}

/**
 * Remove a row's Drive copy: trash it, or rename it to {name}.removed.{ext}
 * so the folder scan doesn't re-adopt it. Missing files are fine.
 */
async function detachDriveCopy(driveFileId, { trash }) {
  if (!driveFileId) return null;
  try {
    if (trash) {
      await googleDrive.trashFile(driveFileId);
      return null;
    }
    const meta = await googleDrive.getFileMetadata(driveFileId);
    const target = detachedFileName(meta.name);
    if (target !== meta.name) await googleDrive.renameFile(driveFileId, target);
    return target;
  } catch (driveError) {
    if (isDriveNotFound(driveError)) return null;
    throw driveError;
  }
}

// GET / — DB rows always; live folder listing + unclassified when Drive is up.
router.get('/', async (req, res) => {
  const { movieId } = req.params;
  try {
    const movie = await loadMovie(movieId);
    if (!movie) return res.status(404).json({ error: 'Movie not found' });
    const common = {
      ready: readyOf(movie),
      azure_configured: movieStorage.isConfigured(),
    };

    if (!googleDrive.isConfigured()) {
      const dbRows = await pool.query(
        'SELECT * FROM movie_files WHERE movie_id = $1 ORDER BY file_kind',
        [movieId]
      );
      return res.json({
        files: dbRows.rows,
        folder: movie.drive_folder_id ? { id: movie.drive_folder_id } : null,
        unclassified: [],
        drive_configured: false,
        ...common,
      });
    }

    // Live scan reconciles rows and surfaces unclassified files.
    try {
      const result = await scanMovie(movieId);
      return res.json({ ...result, drive_configured: true, ...common });
    } catch (driveError) {
      logError(driveError, req, { operation: 'movie_files_scan', movieId });
      const dbRows = await pool.query(
        'SELECT * FROM movie_files WHERE movie_id = $1 ORDER BY file_kind',
        [movieId]
      );
      return res.json({
        files: dbRows.rows,
        folder: movie.drive_folder_id ? { id: movie.drive_folder_id } : null,
        unclassified: [],
        drive_configured: true,
        drive_error: driveError.message,
        ...common,
      });
    }
  } catch (error) {
    logError(error, req, { operation: 'get_movie_files', movieId });
    res.status(500).json({ error: error.message });
  }
});

