/**
 * Per-movie Drive file management: /api/movies/:movieId/files
 *
 * Mounted with mergeParams so :movieId is available. Drive-dependent endpoints
 * return 503 when Google Drive is not configured; GET degrades to DB rows with
 * a drive_error flag so the UI always renders known status.
 */

const express = require('express');
const { pool } = require('../models/database');
const { logError } = require('../utils/logger');
const googleDrive = require('../services/googleDrive');
const { proxyDriveMedia } = require('../services/driveMediaProxy');
const transcodeQueue = require('../services/transcodeQueue');
const {
  convertSrtToVtt,
  parseSubtitles,
  serializeSrt,
  serializeVtt,
} = require('../utils/subtitles');
const { scanMovie, upsertFileRow } = require('../services/movieFileScanner');
const {
  MAX_SUBTITLE_BYTES,
  readSubtitleText,
  cacheSubtitleTextSafe,
} = require('../services/subtitleCache');
const {
  conventionFileName,
  detachedFileName,
  extensionOf,
  isVideoFile,
  SUBTITLE_EXTENSIONS,
  FILE_KINDS,
} = require('../utils/movieFileNaming');

const router = express.Router({ mergeParams: true });

const SUBTITLE_KINDS = ['subtitles_cs', 'subtitles_en'];
// Languages accepted by the /subtitles/:lang routes (subtitles_{lang} kinds).
// Synced variants are machine-generated by the sync worker but serve/edit the same way.
const SUBTITLE_LANGS = ['cs', 'en', 'cs_synced', 'en_synced'];
// File kinds that are playable video and can be streamed to the browser.
const STREAMABLE_KINDS = ['movie', 'movie_proxy'];

function notConfigured(res) {
  return res.status(503).json({ error: 'Google Drive is not configured' });
}

/** Drive "file not found" (already deleted/trashed elsewhere). */
function isDriveNotFound(error) {
  return error?.code === 404 || error?.response?.status === 404;
}

/** The manual "files ready" mark from a loadMovie() row, or null. */
function readyOf(movie) {
  return movie.files_ready_at
    ? { at: movie.files_ready_at, by: movie.files_ready_by || null }
    : null;
}

/**
 * Ensure a file's type matches the kind slot it will occupy:
 * subtitle kinds require .srt/.vtt; the movie kind requires a video file.
 * Returns an error string, or null if valid.
 */
function validateKindForFile(fileKind, fileName, mimeType) {
  const ext = extensionOf(fileName);
  if (
    (SUBTITLE_KINDS.includes(fileKind) || fileKind.endsWith('_synced')) &&
    !SUBTITLE_EXTENSIONS.includes(ext)
  ) {
    return 'Subtitles must be .srt or .vtt';
  }
  if (fileKind === 'movie' && !isVideoFile(fileName, mimeType)) {
    return 'Movie asset must be a video file';
  }
  if (fileKind === 'movie_proxy' && ext !== 'mp4') {
    return 'Preview proxy must be an .mp4';
  }
  return null;
}

/** Load a movie row with edition_year, or null. */
async function loadMovie(movieId) {
  const res = await pool.query(
    `SELECT m.id, m.name_cs, m.name_en, m.drive_folder_id, m.files_ready_at,
            m.files_ready_by, e.year AS edition_year
     FROM movies m JOIN editions e ON m.edition_id = e.id
     WHERE m.id = $1`,
    [movieId]
  );
  return res.rows[0] || null;
}

function subtitleMime(ext) {
  return ext === 'vtt' ? 'text/vtt' : 'application/x-subrip';
}

/** Read a subtitle row's text through the cache (Drive only on a miss). */
function readRowText(row) {
  return readSubtitleText(row.drive_file_id, { expectedMd5: row.md5_checksum || null });
}

/** Cache freshly written subtitle bytes; failures are only logged. */
function cacheWritten(req, movieId, meta, body) {
  return cacheSubtitleTextSafe(
    meta.id,
    { bytes: body, md5: meta.md5Checksum || null },
    (cacheError) => logError(cacheError, req, { operation: 'cache_subtitle_text', movieId })
  );
}

/**
 * Guard an in-place overwrite: compare the file's current Drive md5 with the
 * md5 the app based its change on. On a mismatch the file was edited outside
 * the app — refresh the pointer row (so the next read re-downloads instead of
 * serving the cached old text) and return the fresh metadata as `changed`.
 */
async function checkDriveUnchanged(movieId, row, baseMd5) {
  const meta = await googleDrive.getFileMetadata(row.drive_file_id);
  if (meta.md5Checksum && baseMd5 && meta.md5Checksum !== baseMd5) {
    await upsertFileRow(movieId, row.file_kind, meta);
    return { changed: meta };
  }
  return { changed: null };
}

/**
 * Mark a subtitle track's open quality flags stale (its file was replaced or
 * removed, so the findings no longer describe it). Non-fatal.
 */
async function staleOpenFlags(req, movieId, lang) {
  try {
    await pool.query(
      `UPDATE subtitle_quality_flags SET status = 'stale'
       WHERE movie_id = $1 AND lang = $2 AND status = 'open'`,
      [movieId, lang]
    );
  } catch (flagError) {
    logError(flagError, req, { operation: 'stale_subtitle_quality_flags', movieId });
  }
}

/** Load the movie_files row for a subtitle language, or null. */
async function loadSubtitleRow(movieId, lang) {
  const row = await pool.query(
    'SELECT * FROM movie_files WHERE movie_id = $1 AND file_kind = $2',
    [movieId, `subtitles_${lang}`]
  );
  return row.rows[0] || null;
}

// GET / — DB rows always; live folder listing + unclassified when Drive is up.
router.get('/', async (req, res) => {
  const { movieId } = req.params;
  try {
    const movie = await loadMovie(movieId);
    if (!movie) return res.status(404).json({ error: 'Movie not found' });

    if (!googleDrive.isConfigured()) {
      const dbRows = await pool.query(
        'SELECT * FROM movie_files WHERE movie_id = $1 ORDER BY file_kind',
        [movieId]
      );
      return res.json({
        files: dbRows.rows,
        folder: movie.drive_folder_id ? { id: movie.drive_folder_id } : null,
        unclassified: [],
        drive_configured: false,
        ready: readyOf(movie),
      });
    }

    // Live scan reconciles rows and surfaces unclassified files.
    try {
      const result = await scanMovie(movieId);
      return res.json({ ...result, drive_configured: true, ready: readyOf(movie) });
    } catch (driveError) {
      logError(driveError, req, { operation: 'movie_files_scan', movieId });
      const dbRows = await pool.query(
        'SELECT * FROM movie_files WHERE movie_id = $1 ORDER BY file_kind',
        [movieId]
      );
      return res.json({
        files: dbRows.rows,
        folder: movie.drive_folder_id ? { id: movie.drive_folder_id } : null,
        unclassified: [],
        drive_configured: true,
        drive_error: driveError.message,
        ready: readyOf(movie),
      });
    }
  } catch (error) {
    logError(error, req, { operation: 'get_movie_files', movieId });
    res.status(500).json({ error: error.message });
  }
});

